const _split = (s) => {
  const m = String(s || "").match(/^(.*?),\s*([A-Za-z]{2})$/);
  return m ? [m[1].trim().toLowerCase(), m[2].toUpperCase()] : [null, null];
};

// Resolve a model-normalized "City, ST" to { metro (ZORI name), cbsa }.
export function resolveMetro(input) {
  if (!input) return null;
  const s = String(input).trim();
  if (!s || s.toUpperCase() === "NONE") return null;
  const key = s.toLowerCase();
  let hit = METRO_XWALK.find((x) => x.z.toLowerCase() === key);
  if (!hit) {
    const [city, st] = _split(s);
    if (city && st) {
      hit =
        METRO_XWALK.find((x) => { const [c, t] = _split(x.z); return c === city && t === st; }) ||
        METRO_XWALK.find((x) => { const [c, t] = _split(x.z); return t === st && c && (c.startsWith(city) || city.startsWith(c)); });
    }
  }
  if (!hit) return null;
  return { metro: hit.z, cbsa: hit.c || undefined };
}
